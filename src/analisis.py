#Esto es un repason y creacion de un calculador de promedio
datos=[10,20,30,40,50]
suma_datos=sum(datos)
num_datos=len(datos)
prom=suma_datos/num_datos
max_datos=max(datos)
min_datos=min(datos)
print(f"Estos son los valores del arreglo {datos}")
print(f"Esta es la suma de esos datos {suma_datos}")
print(f"Es la cantidad de datos del arreglo {num_datos}")
print(f"Este es el promedio de los datos {prom}")   
print(f"Este es el maximo de los datos {max_datos}")
print(f"Este es el minimo de los datos {min_datos}")